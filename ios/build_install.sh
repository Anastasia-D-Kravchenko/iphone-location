#!/bin/zsh
# Builds the "Location" iPhone app and installs it on the plugged-in iPhone.
# Run again every 7 days (free Apple ID signing expires).
set -euo pipefail
cd "$(dirname "$0")"

# Personal settings (device IDs, team, bundle id): copy local.env.example to local.env.
[[ -f local.env ]] || { echo "Missing ios/local.env — copy local.env.example and fill it in."; exit 1; }
set -a; source ./local.env; set +a

DEVICE="${1:-$IPHONE_UDID}"
TOKEN_FILE=../.token
if [[ ! -f $TOKEN_FILE ]]; then
  python3 -c "import secrets; print(secrets.token_urlsafe(24))" > $TOKEN_FILE
  chmod 600 $TOKEN_FILE
fi
HOST="$(scutil --get LocalHostName).local:8765"
TS_IP="$(tailscale ip -4 2>/dev/null | head -1 || true)"
[[ -n $TS_IP ]] && HOST="$HOST, $TS_IP:8765"

cat > LocationRemote/Config.swift <<EOF
// Generated by build_install.sh. Do not share: the token lets anyone on your Wi-Fi move your location.
enum Config {
    static let host = "$HOST"
    static let token = "$(cat $TOKEN_FILE)"
}
EOF
chmod 600 LocationRemote/Config.swift

[[ -f LocationRemote/Assets.xcassets/AppIcon.appiconset/icon.png ]] || python3 make_icon.py

xcodegen generate --quiet
xcodebuild -project LocationRemote.xcodeproj -scheme LocationRemote -configuration Release \
  -destination "id=$DEVICE" -derivedDataPath build -allowProvisioningUpdates -quiet build

APP=build/Build/Products/Release-iphoneos/LocationRemote.app
xcrun devicectl device install app --device "$DEVICE" "$APP"
[[ -n "${NO_LAUNCH:-}" ]] || xcrun devicectl device process launch --device "$DEVICE" "$BUNDLE_ID" || true
echo "Installed. Mac address in the app: $HOST"
